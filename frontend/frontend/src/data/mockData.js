export function daysBetween(dateStr) { if (!dateStr) return 0; const d = new Date(dateStr); if (Number.isNaN(d.getTime())) { return 0; } const today = new Date(); const start = new Date( d.getFullYear(), d.getMonth(), d.getDate() ); const end = new Date( today.getFullYear(), today.getMonth(), today.getDate() ); return Math.max( 0, Math.floor((end - start) / 86400000) ); }


export function fmtDate(dateStr, lang = "en") {
  const d = new Date(dateStr);

  return d.toLocaleDateString(
    lang === "ur" ? "ur-PK" : "en-GB",
    {
      day: "2-digit",
      month: "short",
      year: "numeric",
    }
  );
}
